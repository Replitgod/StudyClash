// Concatenate the 2026-09-18 migrations into one paste-ready file.
//
// Generated rather than hand-copied, so the bundle cannot drift from the
// migrations it carries. Run: node scripts/build-sql-bundle-2026-09-18.mjs

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const MIGRATIONS = join(process.cwd(), "supabase", "migrations");
const OUT_DIR = join(process.cwd(), "docs", "sql");
const OUT = join(OUT_DIR, "apply-2026-09-18.sql");

/** 01 creates public.deck_is_readable, which 02's flashcards policy calls. */
const FILES = ["20260918_01_privacy_lockdown.sql", "20260918_02_study_signals.sql"];

const DOLLAR = "$" + "$";
const RULE = "-- " + "=".repeat(70);

const HEADER = `-- AceDecks: apply 2026-09-18
--
-- Two migrations, in the order they must run. Generated by
-- scripts/build-sql-bundle-2026-09-18.mjs from supabase/migrations/ -- edit
-- those, not this.
--
-- 01  PRIVACY. Closes read access that let anyone holding the public anon
--     key download every student's notes and mistakes, and stops a student
--     from setting their own plan to Pro. Apply this first, and soon.
-- 02  STUDY SIGNALS. Why-wrong notes on questions, real flashcards with
--     per-student review state, confidence on answers, the onboarding
--     profile columns, and the mistake-explanation cache. The app runs
--     without it (every new column is read with a fallback), but flashcards,
--     confidence tracking and onboarding only persist once it is applied.
--
-- Every statement is idempotent: running this twice is safe, and so is
-- re-running it after applying part of it. Every statement was parsed with
-- PostgreSQL's own grammar (libpg_query) before this file was generated.

${RULE}
-- PREFLIGHT
${RULE}

do ${DOLLAR}
begin
  if to_regclass('public.decks') is null or to_regclass('public.matches') is null then
    raise exception 'AceDecks: core tables are missing.'
      using hint = 'This database is not an AceDecks database, or the early migrations were never applied.';
  end if;

  if to_regclass('public.classroom_rooms') is null then
    raise exception 'AceDecks: table public.classroom_rooms is missing.'
      using hint = 'Apply supabase/migrations/20260709_growth_foundations.sql first.';
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'decks' and column_name = 'is_public'
  ) then
    raise exception 'AceDecks: decks.is_public is missing.'
      using hint = 'Apply supabase/migrations/20260831_public_deck_sharing.sql first.';
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'profiles' and column_name = 'roasts_enabled'
  ) then
    raise exception 'AceDecks: profiles.roasts_enabled is missing.'
      using hint = 'Apply supabase/migrations/20260802_roast_preferences.sql first.';
  end if;
end
${DOLLAR};
`;

const FOOTER = `

${RULE}
-- WHAT YOU SHOULD SEE AFTERWARDS
${RULE}
--
-- 1. Browser profile updates are limited to two columns. This should list
--    exactly display_name and roasts_enabled:
--
--      select column_name from information_schema.column_privileges
--      where table_schema = 'public' and table_name = 'profiles'
--        and grantee = 'authenticated' and privilege_type = 'UPDATE';
--
-- 2. An anonymous read of decks returns only published ones. In the SQL
--    editor, as the anon role:
--
--      set role anon;
--      select count(*) from public.decks where coalesce(is_public, false) = false;
--      reset role;
--
--    should be 0 (unless a deck has an active challenge link or is a
--    classroom deck, which are shared on purpose).
--
-- 3. The new tables exist:
--
--      select to_regclass('public.flashcards'), to_regclass('public.flashcard_state'),
--             to_regclass('public.mistake_explanations');
`;

let out = HEADER;
for (const file of FILES) {
  const sql = readFileSync(join(MIGRATIONS, file), "utf8").replace(/\r\n/g, "\n");
  out += `\n\n${RULE}\n-- FILE: ${file}\n${RULE}\n\n${sql.trim()}\n`;
}
out += FOOTER;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, out, "utf8");

console.log(`wrote ${OUT}`);
console.log(`${out.split("\n").length} lines, ${FILES.length} migrations`);
